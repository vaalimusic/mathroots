// =========================================================================
// 2. Dynamic Algorithmic Infinite Problem Generator
// Позволяет мгновенно генерировать сотни уникальных вариантов задач
// с гарантированно целыми/красивыми решениями, детальными шагами и ловушками!
// =========================================================================

export function generateDynamicWorkoutProblem(category: string, seedIndex: number): WorkoutProblem {
  const randInt = (min: number, max: number) =>
    Math.floor(Math.random() * (max - min + 1)) + min;

  if (category === 'parentheses' || (category === 'all' && seedIndex % 5 === 0)) {
    // Генератор: a(x) + c при x = k  (ловушка со скобками и умножением)
    const a = randInt(2, 6);
    const xVal = randInt(2, 7);
    const c = randInt(3, 15);
    const correctMult = a * xVal;
    const correctAns = correctMult + c;
    const concatenatedTrap = parseInt(`${a}${xVal}`, 10) + c;
    const addFirstTrap = a * (xVal + c);

    return {
      id: `dyn_paren_${seedIndex}_${Date.now()}`,
      category: 'parentheses',
      categoryTitle: 'Скобки и неявное умножение',
      difficulty: 'basic',
      title: `Вычисление подстановки: ${a}(${xVal}) + ${c}`,
      formula: `${a}(${xVal}) + ${c} = ?`,
      question: `Каково точное значение выражения ${a}(${xVal}) + ${c}? Обрати внимание на число перед скобкой!`,
      options: [
        `${correctAns} — скобка означает умножение: ${a} · ${xVal} = ${correctMult}, затем + ${c} = ${correctAns}`,
        `${concatenatedTrap} — если склеить цифры как в десятичной записи (${a}${xVal} + ${c})`,
        `${addFirstTrap} — если сначала сложить ${xVal} + ${c} = ${xVal + c}, затем умножить на ${a}`,
        `${correctMult} — если забыть прибавить свободное число ${c}`,
      ],
      correctIndex: 0,
      expectedAnswer: String(correctAns),
      explanation: `Число ${a} перед скобкой (${xVal}) означает умножение: ${a} · ${xVal} = ${correctMult}. Сначала выполняется умножение, затем сложение с ${c}: ${correctMult} + ${c} = ${correctAns}.`,
      stepByStepBreakdown: [
        `Шаг 1: Раскрываем смысл неявного умножения: ${a}(${xVal}) = ${a} · ${xVal}`,
        `Шаг 2: Умножаем: ${a} · ${xVal} = ${correctMult}`,
        `Шаг 3: Прибавляем слагаемое: ${correctMult} + ${c} = ${correctAns}`,
        `Шаг 4: Итоговый ответ: ${correctAns} (Никакого склеивания цифр!)`,
      ],
      whyRule: 'Приоритет операций: умножение предшествует сложению, скобка без знака означает произведение.',
      cognitiveTrap: {
        myth: `«${a}(${xVal}) читается как ${a}${xVal}»`,
        whyBrainFails: 'Логика позиционной записи чисел вместо алгебраического умножения.',
        counterExample: `${a} коробок по ${xVal} предметов дают ${a * xVal} предметов, а не ${a}${xVal}!`,
      },
    };
  }

  if (category === 'linear' || (category === 'all' && seedIndex % 5 === 1)) {
    // Генератор: ax + b = c (с красивым целым корнем x)
    const a = randInt(2, 5);
    const x = randInt(2, 9);
    const b = randInt(1, 15);
    const c = a * x + b;

    return {
      id: `dyn_lin_${seedIndex}_${Date.now()}`,
      category: 'linear',
      categoryTitle: 'Линейные уравнения',
      difficulty: 'basic',
      title: `Линейное уравнение: ${a}x + ${b} = ${c}`,
      formula: `${a}x + ${b} = ${c} \\implies x = ?`,
      question: `Найдите корень уравнения ${a}x + ${b} = ${c}:`,
      options: [
        `x = ${x} — вычитаем ${b} (${a}x = ${c - b}), затем делим на ${a} (x = ${x})`,
        `x = ${x + 2} — ошибка вычитания`,
        `x = ${Math.round((c + b) / a)} — сложили ${c} + ${b} вместо вычитания`,
        `x = ${c - b} — забыли разделить на коэффициент ${a}`,
      ],
      correctIndex: 0,
      expectedAnswer: String(x),
      explanation: `Чтобы решить ${a}x + ${b} = ${c}, сначала вычитаем ${b} из обеих частей: ${a}x = ${c - b}. Затем делим обе части на ${a}: x = ${c - b} / ${a} = ${x}. Проверка: ${a}(${x}) + ${b} = ${a * x} + ${b} = ${c}.`,
      stepByStepBreakdown: [
        `Шаг 1: Вычитаем ${b} из обеих частей: ${a}x = ${c} - ${b} = ${c - b}`,
        `Шаг 2: Делим обе части на коэффициент перед x: x = ${c - b} / ${a}`,
        `Шаг 3: Получаем точный корень: x = ${x}`,
        `Шаг 4: Проверка: ${a} · (${x}) + ${b} = ${a * x + b} == ${c} ✔`,
      ],
      whyRule: 'Сохранение равенства при вычитании равных величин и делении на ненулевое число.',
    };
  }

  if (category === 'quadratic' || (category === 'all' && seedIndex % 5 === 2)) {
    // Генератор: (x - p)(x - q) = 0 => x² - (p+q)x + pq = 0
    const p = randInt(1, 5);
    const q = randInt(p + 1, 7);
    const b = -(p + q);
    const c = p * q;

    return {
      id: `dyn_quad_${seedIndex}_${Date.now()}`,
      category: 'quadratic',
      categoryTitle: 'Квадратные уравнения',
      difficulty: 'basic',
      title: `Квадратное уравнение: x² ${b}x + ${c} = 0`,
      formula: `x^2 ${b}x + ${c} = 0 \\implies x_1, x_2 = ?`,
      question: `Чему равны корни приведенного квадратного уравнения x² ${b}x + ${c} = 0?`,
      options: [
        `x₁ = ${p}, x₂ = ${q} — по теореме Виета сумма ${p + q}, произведение ${c}`,
        `x₁ = ${-p}, x₂ = ${-q} — знаки перепутаны`,
        `x₁ = 1, x₂ = ${c} — сумма не сходится`,
        `x₁ = ${p + 1}, x₂ = ${q - 1} — сумма сходится, произведение нет`,
      ],
      correctIndex: 0,
      expectedAnswer: `${p}, ${q}`,
      explanation: `Разложим уравнение на множители: (x - ${p})(x - ${q}) = 0. Произведение равно нулю, когда хотя бы один множитель равен нулю: x = ${p} или x = ${q}.`,
      stepByStepBreakdown: [
        `Шаг 1: Ищем два числа с суммой ${p + q} и произведением ${c}`,
        `Шаг 2: Это числа ${p} и ${q}`,
        `Шаг 3: Раскладываем: (x - ${p})(x - ${q}) = 0`,
        `Шаг 4: Приравниваем каждую скобку к нулю: x₁ = ${p}, x₂ = ${q}`,
      ],
      whyRule: 'Теорема о нулевом произведении: a · b = 0 <=> a = 0 или b = 0.',
    };
  }

  if (category === 'fractions' || (category === 'all' && seedIndex % 9 === 3)) {
    // Генератор: n / a + m / b
    const a = randInt(2, 5);
    const b = randInt(6, 9);
    const num1 = 1;
    const num2 = 1;
    // Общий знаменатель
    const gcd = (x: number, y: number): number => (!y ? x : gcd(y, x % y));
    const lcm = (a * b) / gcd(a, b);
    const multA = lcm / a;
    const multB = lcm / b;
    const sumNum = num1 * multA + num2 * multB;

    return {
      id: `dyn_frac_${seedIndex}_${Date.now()}`,
      category: 'fractions',
      categoryTitle: 'Дроби и пропорции',
      difficulty: 'basic',
      title: `Сложение долей: 1/${a} + 1/${b}`,
      formula: `\\frac{1}{${a}} + \\frac{1}{${b}} = ?`,
      question: `Вычислите сумму дробей 1/${a} + 1/${b}:`,
      options: [
        `${sumNum}/${lcm} — общий знаменатель ${lcm}: (${multA} + ${multB})/${lcm}`,
        `2/${a + b} — прямое сложение числителей и знаменателей (ошибка)`,
        `1/${lcm} — не сложены числители`,
        `${multA + multB}/${a * b} — без сокращения знаменателя`,
      ],
      correctIndex: 0,
      expectedAnswer: `${sumNum}/${lcm}`,
      explanation: `Общий знаменатель для ${a} и ${b} равен ${lcm}. Приводим дроби: 1/${a} = ${multA}/${lcm}, а 1/${b} = ${multB}/${lcm}. Сумма равна ${sumNum}/${lcm}.`,
      stepByStepBreakdown: [
        `Шаг 1: Находим НОК(${a}, ${b}) = ${lcm}`,
        `Шаг 2: Дополнительный множитель для первой дроби: ${lcm} / ${a} = ${multA}`,
        `Шаг 3: Дополнительный множитель для второй дроби: ${lcm} / ${b} = ${multB}`,
        `Шаг 4: Складываем: (${multA} + ${multB}) / ${lcm} = ${sumNum}/${lcm}`,
      ],
      whyRule: 'Сложение дробей возможно только после приведения к одинаковому знаменателю.',
    };
  }

  if (category === 'systems' || (category === 'all' && seedIndex % 9 === 4)) {
    // Генератор систем: x + y = S, x - y = D
    const x = randInt(4, 9);
    const y = randInt(1, x - 1);
    const S = x + y;
    const D = x - y;

    return {
      id: `dyn_sys_${seedIndex}_${Date.now()}`,
      category: 'systems',
      categoryTitle: 'Системы уравнений',
      difficulty: 'basic',
      title: `Система: x + y = ${S}, x - y = ${D}`,
      formula: `\\begin{cases} x + y = ${S} \\\\ x - y = ${D} \\end{cases} \\implies (x, y) = ?`,
      question: `Найдите пару решений (x, y) для системы уравнений:`,
      options: [
        `(${x}, ${y}) — складываем: 2x = ${S + D} => x = ${x}, затем y = ${S} - ${x} = ${y}`,
        `(${x + 1}, ${y - 1}) — сумма сходится, разность нет`,
        `(${y}, ${x}) — значения x и y перепутаны местами`,
        `(${Math.round(S / 2)}, ${Math.round(D / 2)}) — без учета второго уравнения`,
      ],
      correctIndex: 0,
      expectedAnswer: `(${x}, ${y})`,
      explanation: `Сложим оба уравнения почленно: (x + y) + (x - y) = ${S} + ${D} => 2x = ${S + D} => x = ${x}. Затем подставим x = ${x} в первое уравнение: ${x} + y = ${S} => y = ${S} - ${x} = ${y}.`,
      stepByStepBreakdown: [
        `Шаг 1: Складываем уравнения почленно: (x + x) + (y - y) = ${S} + ${D}`,
        `Шаг 2: Получаем: 2x = ${S + D}`,
        `Шаг 3: Находим x = ${S + D} / 2 = ${x}`,
        `Шаг 4: Подставляем в x + y = ${S}: ${x} + y = ${S} => y = ${y}`,
        `Шаг 5: Ответ в виде упорядоченной пары: (${x}, ${y})`,
      ],
      whyRule: 'Метод алгебраического сложения сохраняет равносильность системы.',
    };
  }

  if (category === 'trigonometry' || (category === 'all' && seedIndex % 9 === 5)) {
    // Генератор: Пифагоровы тройки (3k, 4k, 5k)
    const k = randInt(1, 4);
    const a = 3 * k;
    const b = 4 * k;
    const c = 5 * k;

    return {
      id: `dyn_trig_${seedIndex}_${Date.now()}`,
      category: 'trigonometry',
      categoryTitle: 'Геометрия и тригонометрия',
      difficulty: 'basic',
      title: `Теорема Пифагора: катеты ${a} и ${b}`,
      formula: `c = \\sqrt{${a}^2 + ${b}^2} = ?`,
      question: `В прямоугольном треугольнике катеты равны ${a} и ${b}. Найдите длину гипотенузы:`,
      options: [
        `${c} — ${a}² + ${b}² = ${a * a} + ${b * b} = ${c * c} => c = √${c * c} = ${c}`,
        `${a + b} — прямое сложение ${a} + ${b} = ${a + b} (грубая ошибка!)`,
        `${c + 1} — арифметическая неточность`,
        `${Math.round((a * b) / 2)} — это площадь треугольника, а не гипотенуза`,
      ],
      correctIndex: 0,
      expectedAnswer: String(c),
      explanation: `По теореме Пифагора c² = a² + b² = ${a}² + ${b}² = ${a * a} + ${b * b} = ${c * c}. Значит, гипотенуза c = √${c * c} = ${c}. Это масштаб классического египетского треугольника 3-4-5 с коэффициентом k = ${k}.`,
      stepByStepBreakdown: [
        `Шаг 1: Вычисляем квадрат первого катета: ${a}² = ${a * a}`,
        `Шаг 2: Вычисляем квадрат второго катета: ${b}² = ${b * b}`,
        `Шаг 3: Складываем квадраты: ${a * a} + ${b * b} = ${c * c}`,
        `Шаг 4: Извлекаем квадратный корень: c = √${c * c} = ${c}`,
      ],
      whyRule: 'Теорема Пифагора: c = √(a² + b²).',
      cognitiveTrap: {
        myth: `«Длина гипотенузы равна просто сумме катетов ${a} + ${b} = ${a + b}»`,
        whyBrainFails: 'Игнорирование геометрии: прямой путь между вершинами всегда короче пути по катетам!',
        counterExample: `Отрезок длины ${c} меньше ломаной ${a} + ${b} = ${a + b}.`,
      },
    };
  }

  if (category === 'calculus' || (category === 'all' && seedIndex % 9 === 6)) {
    // Генератор: производная (a x^n + b x)'
    const a = randInt(2, 4);
    const n = randInt(2, 4);
    const b = randInt(2, 9);
    const coeff = a * n;
    const newPower = n - 1;
    const powerStr = newPower === 1 ? 'x' : `x^${newPower}`;

    return {
      id: `dyn_calc_${seedIndex}_${Date.now()}`,
      category: 'calculus',
      categoryTitle: 'Производные и пределы',
      difficulty: 'basic',
      title: `Производная функции: (${a}x^${n} + ${b}x)'`,
      formula: `(${a}x^${n} + ${b}x)' = ?`,
      question: `Найдите производную степенного полинома f(x) = ${a}x^${n} + ${b}x:`,
      options: [
        `${coeff}${powerStr} + ${b} — показатель степени ${n} сносится как множитель: ${a} · ${n} = ${coeff}, степень понижается на 1`,
        `${a}x^${newPower} + ${b} — забыли умножить на старый показатель ${n}`,
        `${coeff}x^${n} + ${b} — не понизили степень`,
        `${coeff}${powerStr} — потеряли производную слагаемого ${b}x`,
      ],
      correctIndex: 0,
      expectedAnswer: `${coeff}${powerStr} + ${b}`,
      explanation: `По правилу дифференцирования степенной функции (x^n)' = n · x^(n-1). Для первого слагаемого: (${a}x^${n})' = ${a} · ${n} · x^(${n}-1) = ${coeff}${powerStr}. Для второго: (${b}x)' = ${b} · 1 = ${b}. Итого: ${coeff}${powerStr} + ${b}.`,
      stepByStepBreakdown: [
        `Шаг 1: Применяем формулу (x^n)' = n · x^(n-1)`,
        `Шаг 2: Дифференцируем ${a}x^${n}: ${a} · ${n} · x^${newPower} = ${coeff}${powerStr}`,
        `Шаг 3: Дифференцируем ${b}x: ${b} · 1 = ${b}`,
        `Шаг 4: Суммируем производные: ${coeff}${powerStr} + ${b}`,
      ],
      whyRule: 'Линейность производной и правило степени: (c · x^n)\' = c · n · x^(n-1).',
    };
  }

  if (category === 'word_problems' || (category === 'all' && seedIndex % 9 === 7)) {
    // Генератор: задача на движение S = v * t
    const v = randInt(40, 80);
    const t = randInt(2, 5);
    const S = v * t;

    return {
      id: `dyn_word_${seedIndex}_${Date.now()}`,
      category: 'word_problems',
      categoryTitle: 'Текстовые задачи',
      difficulty: 'basic',
      title: `Движение со скоростью ${v} км/ч в течение ${t} часов`,
      formula: `S = v \\cdot t = ${v} \\cdot ${t} = ?`,
      question: `Автомобиль двигался с постоянной скоростью ${v} км/ч ровно ${t} ч. Какое расстояние преодолел автомобиль?`,
      options: [
        `${S} км — расстояние равно произведению скорости на время: ${v} · ${t} = ${S} км`,
        `${v + t} км — сложение скорости со временем (разные размерности!)`,
        `${Math.round(v / t)} км — деление скорости на время`,
        `${S - 20} км — арифметическая погрешность`,
      ],
      correctIndex: 0,
      expectedAnswer: `${S} км`,
      explanation: `Формула пути при равномерном прямолинейном движении: S = v · t. Подставляем значения: S = ${v} км/ч · ${t} ч = ${S} км.`,
      stepByStepBreakdown: [
        `Шаг 1: Записываем физическую формулу пути: S = v · t`,
        `Шаг 2: Определяем параметры: скорость v = ${v} км/ч, время t = ${t} ч`,
        `Шаг 3: Перемножаем величины: ${v} · ${t} = ${S}`,
        `Шаг 4: Указываем размерность: ${S} километров`,
      ],
      whyRule: 'Физический закон равномерного прямолинейного движения.',
      realWorldAnalogy: `Каждый час машина проезжает ${v} км. За ${t} таких часов накопится ${t} отрезков по ${v} км.`,
    };
  }

  // Fallback: Powers generator a^m · a^n
  const base = randInt(2, 4);
  const m = randInt(2, 4);
  const n = randInt(2, 4);
  const totalPower = m + n;
  const powerVal = Math.pow(base, totalPower);

  return {
    id: `dyn_pow_${seedIndex}_${Date.now()}`,
    category: 'powers',
    categoryTitle: 'Степени и корни',
    difficulty: 'basic',
    title: `Свойство степени: ${base}^${m} · ${base}^${n}`,
    formula: `${base}^${m} \\cdot ${base}^${n} = ?`,
    question: `Чему равно выражение ${base}^${m} · ${base}^${n}?`,
    options: [
      `${base}^${totalPower} = ${powerVal} — показатели степеней складываются: ${m} + ${n} = ${totalPower}`,
      `${base}^${m * n} — показатели перемножились (ошибка)`,
      `${base * base}^${totalPower} — основания перемножились`,
      `${base}^${Math.abs(m - n)} — показатели вычлись`,
    ],
    correctIndex: 0,
    expectedAnswer: String(powerVal),
    explanation: `При умножении степеней с одинаковым основанием показатели складываются: a^m · a^n = a^(m+n). Здесь ${base}^(${m}+${n}) = ${base}^${totalPower} = ${powerVal}.`,
    stepByStepBreakdown: [
      `Шаг 1: Основание ${base} одинаковое в обоих множителях`,
      `Шаг 2: Складываем показатели: ${m} + ${n} = ${totalPower}`,
      `Шаг 3: Получаем степень: ${base}^${totalPower}`,
      `Шаг 4: Вычисляем числовое значение: ${powerVal}`,
    ],
    whyRule: 'Свойство произведения степеней с равными основаниями.',
  };
}

// Генерация пула из сотен задач (сочетание мастер-задач и параметрических генераторов)
export function getWorkoutProblems(category: string = 'all', count: number = 20): WorkoutProblem[] {
  let matchedHandcrafted = HANDCRAFTED_PROBLEMS;
  if (category !== 'all') {
    matchedHandcrafted = HANDCRAFTED_PROBLEMS.filter((p) => p.category === category);
  }

  const result: WorkoutProblem[] = [...matchedHandcrafted];

  // Дополняем динамическими задачами до нужного количества
  let seed = 1;
  while (result.length < count) {
    result.push(generateDynamicWorkoutProblem(category, seed++));
  }

  // Перемешиваем детерминированно для разнообразия
  return result.slice(0, count);
}
